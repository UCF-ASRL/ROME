function C = paper_style()
%PAPER_STYLE  House style for every figure in my papers. Call once, before drawing.
%
%   C = PAPER_STYLE() sets the MATLAB graphics defaults listed below and returns
%   the colour palette as an 8x3 matrix, rows in the order they are to be used:
%       C(1,:) blue        C(5,:) purple
%       C(2,:) orange      C(6,:) sky blue
%       C(3,:) green       C(7,:) yellow
%       C(4,:) vermilion   C(8,:) black
%   This is the Okabe-Ito palette (Okabe and Ito, "Color Universal Design",
%   2008; Wong, Nature Methods 8:441, 2011), chosen because all eight colours
%   stay distinguishable under the common forms of colour-vision deficiency
%   and in greyscale print. MATLAB's 'g' (pure lime green) and 'r' are not used.
%
%   The rules the defaults implement are in PLOT_STYLE_RULES.md beside this
%   file. In short: draw every figure at the size it will be printed
%   (PAPER_FIGURE), 8 pt minimum text, axis labels with units in square
%   brackets, no in-panel titles (the panel letter only), 1.2 pt data lines,
%   black dashed references, grid and box on, export with PAPER_EXPORT.
%
%   Pair with:  fig = paper_figure('third')   % or 'half', 'full', or [w h] in inches
%               paper_export(fig, 'name.pdf')  % vector PDF + 300 dpi PNG twin

C = [  0 114 178;    % blue
     230 159   0;    % orange
       0 158 115;    % green
     213  94   0;    % vermilion
     204 121 167;    % purple
      86 180 233;    % sky blue
     240 228  66;    % yellow
       0   0   0] / 255;

set(groot, ...
    'DefaultAxesColorOrder',            C, ...
    'DefaultAxesFontName',              'Helvetica', ...
    'DefaultTextFontName',              'Helvetica', ...
    'DefaultAxesFontSize',              8, ...
    'DefaultTextFontSize',              8, ...
    'DefaultLegendFontSize',            7, ...
    'DefaultAxesTitleFontWeight',       'bold', ...
    'DefaultAxesTitleFontSizeMultiplier', 1.1, ...
    'DefaultLineLineWidth',             1.2, ...
    'DefaultAxesLineWidth',             0.5, ...
    'DefaultAxesBox',                   'on', ...
    'DefaultAxesXGrid',                 'on', ...
    'DefaultAxesYGrid',                 'on', ...
    'DefaultAxesGridAlpha',             0.15, ...
    'DefaultAxesMinorGridAlpha',        0.10, ...
    'DefaultAxesTickDir',               'in', ...
    'DefaultFigureColor',               'w', ...
    'DefaultAxesColor',                 'w', ...
    'DefaultLegendBox',                 'on', ...
    'DefaultLegendEdgeColor',           [0.6 0.6 0.6]);
end
